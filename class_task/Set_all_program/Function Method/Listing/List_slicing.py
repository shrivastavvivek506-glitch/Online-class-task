print("//Example of list slicing")

# Example 1
my_list = [1, 2, 3, 4, 5]
print(my_list[1:4])  # output: [2, 3, 4]

# Example 2
my_list2 = ["apple", "banana", "cherry", "date"]
print(my_list2[0:3]) # output: ["apple", "banana", "cherry"]

# Example 3
my_list3 = [10, 20, 30, 40, 50]
print(my_list3[2:5]) # output: [30, 40, 50]

# Example 4
my_list4 = ["red", "green", "blue", "yellow"]
print(my_list4[1:3]) # output: ["green", "blue"]

# Example 5
my_list5 = [100, 200, 300, 400, 500]
print(my_list5[0:5]) # output: [100, 200, 300, 400, 500]

# Example 6
my_list6 = ["cat", "dog", "fish", "bird"]
print(my_list6[1:4]) # output: ["dog", "fish", "bird"]

# Example 7
my_list7 = [1, 3, 455, 7, 656]
print(my_list7[2:5]) # output: [455, 7, 656]

# Example 8
my_list8 = ["Monday", "Tuesday", "Wednesday", "Thursday"]
print(my_list8[0:3:3]) # output: ["Monday", "Thursday"]

#Example 9
my_list9 = [10, 20, 30, 40, 50]
print(my_list9[1:4:1]) # output: [20, 30, 40]

#Example 10
my_list10 = ["sun", "moon", "stars", "clouds"]
print(my_list10[0:4:2]) # output: ["sun", "stars"]
